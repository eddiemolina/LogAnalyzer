using System;
using System.IO;
using System.Collections.Generic;
class LogAnalyzer
{
    static void Main() 
    {
        // This is the file that is being read by the program.
        string logPath = "C:\\Users\\Eddie Molina\\Desktop\\C# Personal Projects\\InternPrep_LogAnalyzer\\InternPrep_LogAnalyzer\\sample-log.txt";

        //Checks is the file exists before running program.
        if (!File.Exists(logPath))
        {
            Console.WriteLine("Log file not found.");
            return;
        }

        //This reads all the lines from the file above and returns an array of strings, where each string is a line from the file.
        string[] lines = File.ReadAllLines(logPath);

        //This is a string that will store the report that is generated and will be used to export report to a file in the future.
        string fullReport;
        string nextLine = "\n";

        //Initialization of of variables for counts.
        int failedLogins = 0;
        int warnings = 0;
        int errors = 0;

        //This string will contain the report of the failed logins by IP as well as suspicious activity.
        string logReport = $"Log Analysis Report:{nextLine}" + $"---------------------------{nextLine}";
        string ipReport = $"Failed Login Attempts:{nextLine}" + $"----------------------------{nextLine}";
        string suspiciousIpReport = $"Suspicious Activity:{nextLine}" + $"----------------------------{nextLine}";


        //This is a dictionary that will store the IP addresses and the number of failed login attempts for each IP.
        Dictionary<string, int> failedLoginIps = new Dictionary<string, int>();

        //For each loop that declares a string variable called line and checks if each line contains a keyword.
        //If the line contains a keyword specified for a counter, the counter is incremented by 1.
        foreach (string line in lines)
        {
            if(line.Contains("FAILED LOGIN"))
            {
                failedLogins++;

                //This takes the line that contains the failed login and splits it into parts.
                string[] parts = line.Split(" ");

                //This takes the last part of the line, which is the IP address.
                string ipAddress = parts[parts.Length - 1];

                //This checks if the IP address exists in the dictionary, if it does, it increments the count for the IP.
                if (failedLoginIps.ContainsKey(ipAddress))
                {
                    failedLoginIps[ipAddress]++;
                } else
                {
                    failedLoginIps[ipAddress] = 1;
                }

            } else if (line.Contains("WARNING"))
            {
                warnings++;
            } else if (line.Contains("ERROR"))
            {
                errors++;
            }
        }

        //Log report is generated based on the counts of the keywords and is stored in a string variable called logReport.
        logReport += "Failed Logins: " + failedLogins + nextLine + "Warnings: " + warnings + nextLine + "Errors: " + errors + nextLine;


        //The dictionary is looped through in order to extract the IP address and the number of failed attempts.
        foreach (KeyValuePair<string, int> entry in failedLoginIps)
        {
            string ipAddress = entry.Key;
            int attemptsCount = entry.Value;

            ipReport += ipAddress + ": " + attemptsCount + nextLine;

            // This check if an IP failed more than one log in attempt and flags it as suspicious activity in the report.
            if (attemptsCount > 1)
            {
                suspiciousIpReport += ipAddress + ": " + attemptsCount + nextLine;
                
            } else if (attemptsCount < 1)
            {
                suspiciousIpReport += "No suspicious activity found.";
            }
           
        }

        //This is the full report that is generated by concatenating the log report, the IP report, and the suspicious activity report.
        fullReport = logReport + nextLine + ipReport + nextLine + suspiciousIpReport + nextLine;


        //This creates a new file called report.text and writes the string variable report to that file. It will be overwritten if a file already exist.
        // The try catch block is used to handle any exceptions and let's the user know if the report was successful or not.
        try
        {
            //This is where the report will be exported to.
            string reportPath = "C:\\Users\\Eddie Molina\\Desktop\\C# Personal Projects\\InternPrep_LogAnalyzer\\InternPrep_LogAnalyzer\\full-report.txt";

            //This writes the full report to the specified path.
            File.WriteAllText(reportPath, fullReport);
            Console.WriteLine("Report has been exported successfully!");
        }
        catch
        {
            Console.WriteLine("Report failed to export.");
        }

    }
}